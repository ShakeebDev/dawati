/// محرك الذكاء الاصطناعي المصغر المطور لتوليد نصوص الدعوات
/// يعتمد على نصوص أدبية رفيعة المستوى يتم تخصيصها بناءً على نوع المناسبة ونبرة النص المطلوبة
class AITextService {
  /// الأساليب المتاحة لتوليد نصوص الدعوة
  static const List<Map<String, String>> tones = [
    {'id': 'poetic', 'label': 'شعري 📜'},
    {'id': 'formal', 'label': 'رسمي 💼'},
    {'id': 'romantic', 'label': 'رومانسي 💕'},
    {'id': 'religious', 'label': 'ديني 🕌'},
    {'id': 'modern', 'label': 'عصري ⚡'},
  ];

  /// الدالة الرئيسية لتوليد النص بناءً على نوع المناسبة والنبرة المطلوبة
  static String generateInvitation({
    required String eventType,
    required String eventName,
    String tone = 'poetic',
  }) {
    switch (eventType) {
      case 'wedding':
        return _generateWeddingInvitation(eventName, tone);
      case 'graduation':
        return _generateGraduationInvitation(eventName, tone);
      case 'birthday':
        return _generateBirthdayInvitation(eventName, tone);
      case 'dinner':
        return _generateDinnerInvitation(eventName, tone);
      default:
        return _generateGeneralInvitation(eventName, tone);
    }
  }

  /// 1. نصوص حفلات الزفاف (Wedding Invitations)
  static String _generateWeddingInvitation(String eventName, String tone) {
    switch (tone) {
      case 'formal':
        return 'بكل التقدير والاعتزاز، نتشرف بدعوتكم لمشاركتنا فرحة العمر وحضور حفل زفاف ($eventName)، سائلين المولى عز وجل أن تكتمل بهجتنا بتشريفكم الأنيق.';
      case 'romantic':
        return 'في ليلة نسجت خيوطها من الحب والوفاء، وتبادلت فيها القلوب وعوداً لا تنتهي.. نتشرف بدعوتكم لتوثيق حكايتنا ومشاركتنا ليلة العمر وزفاف ($eventName)، ليكون حضوركم شاهداً على رباط المودة المقدس.';
      case 'religious':
        return 'بسم الله والحمد لله، وببركة من الله نعلن الفرح ونرجو منه تمام القبول.. بموجب قوله تعالى "ومن آياته أن خلق لكم من أنفسكم أزواجاً لتسكنوا إليها وجعل بينكم مودة ورحمة"، نتشرف بدعوتكم لحضور حفل زفاف ($eventName)، شاكرين لكم دعاءكم ومشاركتكم فرحتنا برضا من الله وتوفيق.';
      case 'modern':
        return 'الحب في الهواء، وحان الوقت للاحتفال! يسعدنا جداً دعوتكم لمشاركتنا ليلتنا الأكثر تميزاً وجاذبية في حفل زفاف ($eventName)، فلنرقص سوياً ولنصنع ذكريات لا تُنسى في ليلة من العمر!';
      case 'poetic':
      default:
        return 'تتعانق الأرواح في ليلة من ليالي العمر، ويغرد السعد في آفاقنا.. نتشرف بدعوتكم لمشاركتنا فرحة زفاف ($eventName) حيث تكتمل بوجودكم أجمل اللحظات وتصاغ من حضوركم أبيات التهاني.';
    }
  }

  /// 2. نصوص حفلات التخرج (Graduation Invitations)
  static String _generateGraduationInvitation(String eventName, String tone) {
    switch (tone) {
      case 'formal':
        return 'يسرنا ويسعدنا أن نتقدم إليكم بوافر التقدير والدعوة لمشاركتنا الاحتفال ببهجة التخرج والنجاح المتميز لـ ($eventName)، حضوركم شرف واعتزاز لنا.';
      case 'romantic':
        return 'بروح ملؤها الشغف والامتنان، وبقلوب تخفق بفرحة الوصول.. نتشرف بدعوتكم لمشاركتنا لحظة الحلم المنتظرة وقطاف ثمار السعي في حفل تخرج ($eventName)، ففرحتنا الكبرى تكتمل بعيونكم الفخورة بنا.';
      case 'religious':
        return 'بفضل من الله ومنّه، وتوفيقه وكرمه بعد جد واجتهاد، يسرنا دعوتكم الكريمة لمشاركتنا شكر نعم الله في حفل تخرج ($eventName)، نسأل الله أن يجعله علماً نافعاً ينير دروب الخير ويوفقه لخدمة دينه.';
      case 'modern':
        return 'لقد فعلناها! انتهى التعب وبدأت الرحلة الحقيقية.. يسعدنا جداً أن نحتفل سوياً ونتشارك اللحظات السعيدة في حفل تخرج ($eventName)، أحضروا طاقتكم وإيجابيتكم ولنستمتع معاً بنجاح اليوم وغدٍ!';
      case 'poetic':
      default:
        return 'بعد سنوات من الكفاح، أشرقت شمس النجاح ونالت الروح من السعي أقصى مرادها.. ندعوكم لمقاسمتنا طرب التخرج وجني ثمار التميز لـ ($eventName)، لتبتهج بسطور إنجازنا قلوبكم المحبة.';
    }
  }

  /// 3. نصوص حفلات أعياد الميلاد (Birthday Invitations)
  static String _generateBirthdayInvitation(String eventName, String tone) {
    switch (tone) {
      case 'formal':
        return 'نتشرف بدعوتكم لحضور حفل استقبال بمناسبة ذكرى ميلاد ($eventName)، حيث نسعد بلقائكم وتكتمل مسرتنا بتواجدكم الفخيم.';
      case 'romantic':
        return 'تتفتح زهور العمر وتتراقص قلوبنا حباً وتفاؤلاً بذكرى ميلاد ($eventName).. ندعوكم لتشاركونا دفء هذه الليلة وضحكاتها الدافئة ونكتب سوياً فصلاً جديداً من فصول الذكريات الجميلة.';
      case 'religious':
        return 'الحمد لله الذي وهبنا من لدنه عمراً وبارك في أيامنا.. ندعوكم بقلوب حامدة لمشاركتنا شكر نعم الله وإدخال السرور بمناسبة ذكرى ميلاد ($eventName)، سائلين المولى عز وجل له عمراً مديداً في طاعته ورضوانه.';
      case 'modern':
        return 'استعدوا لأجمل ليلة احتفال! نحتفل بعام جديد وخطوة جديدة من العمر السعيد بمناسبة عيد ميلاد ($eventName)، ننتظركم بجرعات من الضحك والموسيقى والذكريات الرائعة التي لا تكتمل إلا بوجودكم!';
      case 'poetic':
      default:
        return 'أشرقت شمس عام جديد، وغرد قمري الفرح فوق غصون التمني.. نشاطركم المحبة وندعوكم للاحتفال بعيد ميلاد ($eventName) المبهج، ليدوم الوصال وتشرق ليلتنا بالضحكات.';
    }
  }

  /// 4. نصوص دعوات العشاء (Dinner Invitations)
  static String _generateDinnerInvitation(String eventName, String tone) {
    switch (tone) {
      case 'formal':
        return 'يسرنا دعوتكم الكريمة لحضور مأدبة عشاء خاصة تقام احتفاءً بـ ($eventName)، متطلعين بشرف لاستقبالكم والترحيب بكم على مائدة المودة واللقاء.';
      case 'romantic':
        return 'على مائدة تجمعنا بالحب والامتنان، ننتظركم لنقتسم الدفء وتفاصيل الأحاديث العذبة في مأدبة عشاء ($eventName)، لنصنع معاً ذكرى دافئة تخلد في القلوب.';
      case 'religious':
        return 'ببركة الله وعلى فضله وكرمه، نتشرف بدعوتكم الكريمة لحضور مأدبة العشاء المقامة شكراً لله واحتفاءً بـ ($eventName)، يطيب بنا اللقاء ويتبارك جمعنا بذكره وشكره.';
      case 'modern':
        return 'طعام رائع، ورفقة أروع، وأوقات لا تُعوض! ندعوكم بحماس لقضاء سهرة مميزة على مأدبة عشاء ($eventName)، لا نحتاج إلا حضوركم الرائع وابتسامتكم الجميلة لنصنع ليلة استثنائية.';
      case 'poetic':
      default:
        return 'على بساط المودة والمحبة والوفاء، يطيب اللقاء ويحلو العشاء.. ننتظر بشغف مجيئكم لحضور مأدبة عشاء ($eventName) حيث الأنس يكتمل بحضوركم العطر وطيب مجالسكم البهية.';
    }
  }

  /// 5. نصوص الدعوات العامة والافتراضية (General Invitations)
  static String _generateGeneralInvitation(String eventName, String tone) {
    switch (tone) {
      case 'formal':
        return 'نتشرف بدعوتكم الكريمة لحضور فعاليتنا المقامة بمناسبة ($eventName)، شاكرين لكم طيب الحضور وتلبية دعوتنا الأنيقة.';
      case 'romantic':
        return 'بكل مشاعر الود والسرور، ندعوكم لمشاركتنا لحظة خاصة جداً للقلوب بمناسبة ($eventName)، فأنتم من يرسم ملامح الفرح على وجه أيامنا السعيدة.';
      case 'religious':
        return 'بسم الله توكلنا، وبكرمه وفضله نسعد بمشاركتكم الفرح.. نتشرف بدعوتكم لحضور فعاليتنا بمناسبة ($eventName)، سائلين الله العلي القدير أن يبارك في جمعنا.';
      case 'modern':
        return 'انضموا إلينا للاحتفال وقضاء وقت ممتع بمناسبة ($eventName)، طاقتكم وإشراقتكم هي كل ما نحتاجه لجعل هذه المناسبة تفوق التوقعات!';
      case 'poetic':
      default:
        return 'أهلاً بمن دانى الوصال بقلبه، وحل نجماً في سماء سرورنا.. ندعوكم بقلوب يملؤها الشوق لمشاركتنا فرحة ($eventName) الغامرة لتورق بحضوركم بساتين بهجتنا.';
    }
  }
}
